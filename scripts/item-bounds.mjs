// Measure every equipment GLB's bounding box (item space, scale 1) into data/item-bounds.json.
// The web uses it to put an item's contact face on a hardpoint (see apps/web/src/model/fit.ts).
//   node scripts/item-bounds.mjs
import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { NodeIO, getBounds } from '@gltf-transform/core';
import { ALL_EXTENSIONS } from '@gltf-transform/extensions';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const dir = join(root, 'apps/web/public/parts');
const manifest = JSON.parse(readFileSync(join(dir, 'manifest.json'), 'utf8'));
const io = new NodeIO().registerExtensions(ALL_EXTENSIONS);
const round = (v) => v.map((x) => Math.round(x * 100) / 100);
const out = {};
for (const [id, file] of Object.entries(manifest.items ?? {}).sort()) {
  const doc = await io.read(join(dir, file));
  const b = getBounds(doc.getRoot().listScenes()[0]);
  out[id] = { min: round(b.min), max: round(b.max) };
}
writeFileSync(join(root, 'data/item-bounds.json'), JSON.stringify({ $comment: 'Generated by scripts/item-bounds.mjs. Item-space AABB at scale 1, x lateral, y up, z forward.', items: out }, null, 1) + '\n');
console.log(`${Object.keys(out).length} items`);
